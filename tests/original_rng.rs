//! Checks the RNG and bean-order ports against the real ROM, frame by frame.

mod support;

use bean_machine::bean_order::ORDER_LEN;
use bean_machine::{gen_bean_orders, Rng};
use support::{addr, frames, recordings};

/// More RNG calls than the game ever makes in one frame (bean order setup uses 257).
const MAX_CALLS_PER_FRAME: usize = 600;

#[test]
fn every_seed_change_is_explained_by_random() {
    for path in recordings() {
        let mut prev: Option<u32> = None;
        let mut changes = 0;
        for (frame, ram) in frames(&path).enumerate() {
            let seed = ram.u32(addr::RNG_SEED);
            if let Some(old) = prev.filter(|&old| old != seed) {
                let mut rng = Rng::new(old);
                let calls = (1..=MAX_CALLS_PER_FRAME).find(|_| {
                    rng.next();
                    rng.seed == seed
                });
                assert!(
                    calls.is_some(),
                    "{}: frame {frame}: seed {old:08X} -> {seed:08X} is not reachable with our Random",
                    path.display()
                );
                changes += 1;
            }
            prev = Some(seed);
        }
        eprintln!("{}: {changes} seed changes, all reproduced", path.display());
    }
}

#[test]
fn bean_orders_match_the_original() {
    let (mut checked, mut skipped) = (0, 0);
    for path in recordings() {
        let mut prev_seed = 0;
        let mut prev_order = vec![0u8; ORDER_LEN];
        let mut prev_p2 = vec![0u8; ORDER_LEN];
        // An order that changed, checked once it holds for a frame (GenPuyoOrder can
        // outlast a video frame, leaving a half-shuffled order in one snapshot), with the
        // seed from before it began.
        let mut pending: Option<usize> = None;
        let mut start_seed: Option<u32> = None;
        // (frames the dealing spanned: vertical blanks may have drawn from the RNG in the
        // middle of it, which whole_matches_run_on_the_engine_alone places)
        let mut spanned = 0;
        for (frame, ram) in frames(&path).enumerate() {
            let p1 = ram.bytes(addr::P1_BEAN_ORDER, ORDER_LEN);
            let p2 = ram.bytes(addr::P2_BEAN_ORDER, ORDER_LEN);
            // Frame 0 has no previous frame (recordings may start from a savestate mid-match).
            // (P2's order can still be dealt the frame after P1's, in 1P vs 2P; alone, it's
            // the CPU's pattern play rewriting it)
            let p1_changed = p1 != prev_order.as_slice();
            let p2_changed = p2 != prev_p2.as_slice();
            let changed = frame > 0 && (p1_changed || p2_changed && start_seed.is_some()) && p1.iter().any(|&b| b != 0);
            if changed {
                start_seed.get_or_insert(prev_seed);
                spanned += 1;
                // (the tutorial copies its own beans into P1's order only)
                pending = (p2 != prev_p2.as_slice() || pending.is_some()).then_some(frame);
            } else if std::mem::take(&mut spanned) > 1 && pending.take().is_some() {
                skipped += 1;
            } else if let (Some(at), Some(seed)) = (pending.take(), start_seed.take()) {
                let (level, mode) = (ram.u8(addr::LEVEL), ram.u8(addr::LEVEL_MODE));
                // The order was generated some RNG calls after that seed.
                let mut start = Rng::new(seed);
                let found = (0..MAX_CALLS_PER_FRAME).any(|_| {
                    let orders = gen_bean_orders(&mut start.clone(), level, mode);
                    start.next();
                    orders.p1.map(|b| b as u8) == *p1 && orders.p2.map(|b| b as u8) == *p2
                });
                assert!(found, "{}: frame {at}: bean order (level {level}, mode {mode}) differs from ours", path.display());
                checked += 1;
            }
            if !changed {
                start_seed = None;
                spanned = 0;
            }
            prev_order.copy_from_slice(p1);
            prev_p2.copy_from_slice(p2);
            prev_seed = ram.u32(addr::RNG_SEED);
        }
    }
    if checked > 0 {
        eprintln!("{checked} bean order(s) generated by the ROM, all identical to ours ({skipped} dealt over several frames)");
    }
}
