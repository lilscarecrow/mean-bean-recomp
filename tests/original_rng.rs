//! Checks the RNG and bean-order ports against the real ROM, frame by frame.

mod support;

use bean_machine::mbm::bean_order::ORDER_LEN;
use bean_machine::mbm::{gen_bean_orders, Rng};
use support::{addr, frames, recordings};

/// More RNG calls than the game ever makes in one frame (bean order setup uses 257).
const MAX_CALLS_PER_FRAME: usize = 600;

#[test]
fn every_seed_change_is_explained_by_random() {
    for path in recordings() {
        let mut prev: Option<u32> = None;
        let mut changes = 0;
        for (frame, ram) in frames(&path).enumerate() {
            let seed = ram.u32(addr::RNG_SEED);
            if let Some(old) = prev.filter(|&old| old != seed) {
                let mut rng = Rng::new(old);
                let calls = (1..=MAX_CALLS_PER_FRAME).find(|_| {
                    rng.next();
                    rng.seed == seed
                });
                assert!(
                    calls.is_some(),
                    "{}: frame {frame}: seed {old:08X} -> {seed:08X} is not reachable with our Random",
                    path.display()
                );
                changes += 1;
            }
            prev = Some(seed);
        }
        eprintln!("{}: {changes} seed changes, all reproduced", path.display());
    }
}

#[test]
fn bean_orders_match_the_original() {
    let mut checked = 0;
    for path in recordings() {
        let mut prev_seed = 0;
        let mut prev_order = vec![0u8; ORDER_LEN];
        for (frame, ram) in frames(&path).enumerate() {
            let p1 = ram.bytes(addr::P1_BEAN_ORDER, ORDER_LEN);
            // Frame 0 has no previous frame (recordings may start from a savestate mid-match).
            if frame > 0 && p1 != prev_order.as_slice() && p1.iter().any(|&b| b != 0) {
                let (level, mode) = (ram.u8(addr::LEVEL), ram.u8(addr::LEVEL_MODE));
                let p2 = ram.bytes(addr::P2_BEAN_ORDER, ORDER_LEN);
                // The order was generated some RNG calls after last frame's seed.
                let mut start = Rng::new(prev_seed);
                let found = (0..MAX_CALLS_PER_FRAME).any(|_| {
                    let orders = gen_bean_orders(&mut start.clone(), level, mode);
                    start.next();
                    orders.p1.map(|b| b as u8) == *p1 && orders.p2.map(|b| b as u8) == *p2
                });
                assert!(found, "{}: frame {frame}: bean order (level {level}, mode {mode}) differs from ours", path.display());
                checked += 1;
            }
            prev_order.copy_from_slice(p1);
            prev_seed = ram.u32(addr::RNG_SEED);
        }
    }
    if checked > 0 {
        eprintln!("{checked} bean order(s) generated by the ROM, all identical to ours");
    }
}
